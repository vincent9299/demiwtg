def templated(name, category):
    key = norm_key(category)
    if key in CATEGORY_DESC:
        d, intro, desc = CATEGORY_DESC[key]
        return d.format(name=name), intro.format(name=name), desc.format(name=name)
    # 兜底：通用模板
    parts = [p for p in key.split(SEP) if p]
    big = parts[-2] if len(parts) >= 2 else (parts[-1] if parts else "虚构角色")
    small = parts[-1] if parts else "虚构角色"
    definition = f"{name}是「{small}」分类下的虚构角色 IP，归属于{big}范畴，是内容创作与授权运营中的可识别角色资产。"
    intro = f"{name}是一个{small}类虚构角色。"
    desc = (f"{name}被归入「{small}」（上级：{big}）的虚构角色分类体系中。"
            f"作为该分类下的代表性实例，它可在内容创作、衍生品开发与跨媒介运营中作为独立 IP 资产被调用与识别。")
