def apply(doc):
    """遍历扁平实例列表，给『虚构角色 IP』实例写富描述。"""
    global n_curated, n_templated
    for inst in doc.get("instances", []):
        cat = inst.get("category") or ""
        if "虚构角色 IP" not in cat:
            continue
        name = inst.get("name")
        key = norm(name)
        if key in curated:
            d, intro, desc = curated[key]
            src = "curated"
            n_curated += 1
        else:
            d, intro, desc = templated(name, cat)
            src = "templated"
            n_templated += 1
        inst["definition"] = d
        inst["intro"] = intro
        inst["desc"] = desc
        inst["source"] = src

