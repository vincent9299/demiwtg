# ---- 收集域内实际 L2 节点及整子树 ----
actual = {}
for p, v in rows:
    if not p.startswith(KN + ' / '):
        continue
    segs = p.split(' / ')
    if len(segs) == 4:
        actual.setdefault(segs[3], []).append((p, v))

def subtree_rows(name):
    pre = KN + ' / ' + name
    return [(p, v) for p, v in rows if p == pre or p.startswith(pre + ' / ')]

def inst_count(name):
    return sum(len(v.split('|')) for p, v in subtree_rows(name) if v.strip())

def row_count(name):
    return len(subtree_rows(name))

missing = [n for n in actual if n not in P and n not in SKIP]
extra = [n for n in P if n not in actual and n not in SKIP]
print(f'域内原生节点数: {len(actual)}（不含 IP 两支）')
print(f'P 覆盖: {len([n for n in P if n in actual])}  遗漏: {len(missing)}  多余: {len(extra)}')
if missing:
    print('⚠ 遗漏:', '、'.join(missing))
if extra:
    print('⚠ 多余:', '、'.join(extra))

stat = Counter()
by_dest = defaultdict(list)
for n in sorted(actual):
    if n in SKIP:
        continue
    op, dom, branch, note = P.get(n, ('UNCOVERED', '', '', ''))
    stat[op] += 1
    by_dest[dom or op].append((n, op, branch, inst_count(n), row_count(n), note))

print('\n动作分布:', dict(stat))
total_inst = sum(inst_count(n) for n in actual if n not in SKIP)
print(f'原生节点总实例: {total_inst}')
for dom in sorted(by_dest):
    items = by_dest[dom]
    ti = sum(x[3] for x in items)
    print(f'\n【{dom}】{len(items)} 节点 / {ti} 实例')
    for n, op, br, ic, rc, note in items:
        print(f'   {op:6} {n} → {br or "—"}  ({rc}行/{ic}实例)  {note}')

